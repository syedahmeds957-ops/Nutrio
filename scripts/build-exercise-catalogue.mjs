/**
 * Builds the workout exercise catalogue from free-exercise-db (public domain,
 * https://github.com/yuhonas/free-exercise-db), pinned to one commit.
 *
 *   node scripts/build-exercise-catalogue.mjs                # data + images
 *   node scripts/build-exercise-catalogue.mjs --images-only  # images + image map only
 *
 * Inputs (hand-written, committed):
 *   packages/workout-core/curation/curated.json  which exercises, and our metadata
 *   packages/workout-core/curation/text/*.json   our own EN/AR names and steps
 * Outputs (generated, committed):
 *   packages/workout-core/src/data/exercises.data.ts
 *   apps/mobile/assets/exercises/<id>-{0,1}.jpg
 *   apps/mobile/src/workout/exerciseImages.ts
 *
 * macOS only: images are resized with `sips`, so no image library is needed.
 * Run by hand after editing the curation; CI never runs it.
 */
import fs from 'fs';
import os from 'os';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const SOURCE_SHA = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const RAW = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${SOURCE_SHA}`;
const IMAGE_WIDTH = 400;
const JPEG_QUALITY = 70;
const LOAD_EQUIPMENT = new Set(['dumbbell', 'barbell', 'kettlebell', 'cable', 'machine', 'ez_bar']);

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const curationDir = path.join(root, 'packages/workout-core/curation');
const dataOut = path.join(root, 'packages/workout-core/src/data/exercises.data.ts');
const assetsDir = path.join(root, 'apps/mobile/assets/exercises');
const imageMapOut = path.join(root, 'apps/mobile/src/workout/exerciseImages.ts');

const imagesOnly = process.argv.includes('--images-only');

function fail(message) {
  console.error(`build-exercise-catalogue: ${message}`);
  process.exit(1);
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function nonEmptyStrings(value) {
  return Array.isArray(value) && value.length > 0 && value.every((s) => typeof s === 'string' && s.trim());
}

const curated = readJson(path.join(curationDir, 'curated.json'));

const response = await fetch(`${RAW}/dist/exercises.json`);
if (!response.ok) fail(`could not download the source dataset (${response.status})`);
const source = new Map((await response.json()).map((record) => [record.id, record]));

const problems = [];
for (const entry of curated) {
  const record = source.get(entry.src);
  if (!record) problems.push(`${entry.id}: source id ${entry.src} not found`);
  else {
    if (record.level === 'expert') problems.push(`${entry.id}: source level is expert`);
    if (record.images.length < 2) problems.push(`${entry.id}: source has fewer than 2 images`);
  }
}

if (!imagesOnly) {
  const textDir = path.join(curationDir, 'text');
  const text = Object.assign(
    {},
    ...fs.readdirSync(textDir).filter((f) => f.endsWith('.json')).sort().map((f) => readJson(path.join(textDir, f)))
  );
  const curatedIds = new Set(curated.map((entry) => entry.id));
  for (const id of Object.keys(text)) if (!curatedIds.has(id)) problems.push(`${id}: text exists but the exercise is not curated`);

  const exercises = curated.map((entry) => {
    const record = source.get(entry.src);
    const t = text[entry.id];
    if (!t) {
      problems.push(`${entry.id}: no text in curation/text/`);
      return null;
    }
    if (!nonEmptyStrings(t.steps_en) || !nonEmptyStrings(t.steps_ar) || !t.name_ar?.trim()) {
      problems.push(`${entry.id}: name_ar, steps_en and steps_ar must all be filled`);
    }
    const timed = entry.timed === true;
    return {
      id: entry.id,
      sourceId: entry.src,
      name: { en: entry.en, ar: t.name_ar },
      instructions: { en: t.steps_en, ar: t.steps_ar },
      pattern: entry.pattern,
      primaryMuscles: record?.primaryMuscles ?? [],
      secondaryMuscles: record?.secondaryMuscles ?? [],
      equipment: entry.eq,
      level: record?.level,
      compound: entry.compound ?? record?.mechanic === 'compound',
      jointLoads: entry.joints,
      timed,
      tracksLoad: !timed && !entry.noLoad && entry.eq.some((item) => LOAD_EQUIPMENT.has(item)),
      ...(entry.harder ? { harder: entry.harder } : {}),
      ...(entry.easier ? { easier: entry.easier } : {}),
    };
  });
  if (problems.length) fail(`\n  ${problems.join('\n  ')}`);

  fs.mkdirSync(path.dirname(dataOut), { recursive: true });
  fs.writeFileSync(
    dataOut,
    [
      '// Generated by scripts/build-exercise-catalogue.mjs. Do not edit by hand:',
      '// change packages/workout-core/curation/ and re-run the script.',
      `// Exercise metadata and images: free-exercise-db (public domain) at ${SOURCE_SHA}.`,
      "import { Exercise } from '../types.js';",
      '',
      `export const EXERCISE_DATA: readonly Exercise[] = ${JSON.stringify(exercises, null, 2)};`,
      '',
    ].join('\n')
  );
  console.log(`wrote ${exercises.length} exercises to ${path.relative(root, dataOut)}`);
} else if (problems.length) {
  fail(`\n  ${problems.join('\n  ')}`);
}

fs.mkdirSync(assetsDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'exercise-images-'));
const wanted = new Set();
for (const entry of curated) {
  const record = source.get(entry.src);
  for (const frame of [0, 1]) {
    const name = `${entry.id}-${frame}.jpg`;
    wanted.add(name);
    const out = path.join(assetsDir, name);
    if (fs.existsSync(out)) continue;
    const imageResponse = await fetch(`${RAW}/exercises/${record.images[frame]}`);
    if (!imageResponse.ok) fail(`${entry.id}: image ${record.images[frame]} failed (${imageResponse.status})`);
    const original = path.join(tmp, name);
    fs.writeFileSync(original, Buffer.from(await imageResponse.arrayBuffer()));
    execFileSync('sips', ['--resampleWidth', String(IMAGE_WIDTH), '-s', 'formatOptions', String(JPEG_QUALITY), original, '--out', out], {
      stdio: 'ignore',
    });
  }
}
fs.rmSync(tmp, { recursive: true, force: true });
for (const file of fs.readdirSync(assetsDir)) {
  if (file.endsWith('.jpg') && !wanted.has(file)) fs.rmSync(path.join(assetsDir, file));
}

fs.mkdirSync(path.dirname(imageMapOut), { recursive: true });
fs.writeFileSync(
  imageMapOut,
  [
    '// Generated by scripts/build-exercise-catalogue.mjs. Do not edit by hand.',
    '// Metro only bundles images it can see in a static require(), hence the long list.',
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    'export const EXERCISE_IMAGES: Record<string, readonly [ImageSourcePropType, ImageSourcePropType]> = {',
    ...curated.map(
      (entry) =>
        `  '${entry.id}': [require('../../assets/exercises/${entry.id}-0.jpg'), require('../../assets/exercises/${entry.id}-1.jpg')],`
    ),
    '};',
    '',
  ].join('\n')
);
console.log(`wrote ${wanted.size} images to ${path.relative(root, assetsDir)} and ${path.relative(root, imageMapOut)}`);
