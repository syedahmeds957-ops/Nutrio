/**
 * Generates the migration that loads usda.foods (see
 * supabase/migrations/20261022000000_usda_foods.sql) from USDA FoodData
 * Central's public-domain bulk downloads: SR Legacy and Foundation Foods.
 *
 *   node scripts/import-usda.mjs [out.sql]
 *   -> supabase/migrations/<UTC timestamp>_usda_foods_data.sql by default
 *
 * Each record goes through per100gFrom() from the dish-breakdown function, the
 * same check the function applied to live API results, so a record without
 * energy and all three macros, or with impossible values, is left out.
 *
 * Foundation Foods is re-released about twice a year: point FOUNDATION_URL at
 * the newest file on https://fdc.nal.usda.gov/download-datasets and run this
 * again to write a fresh snapshot migration. SR Legacy is frozen (2018).
 */

import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(fileURLToPath(new URL('.', import.meta.url)), '..');

const DATASETS = 'https://fdc.nal.usda.gov/fdc-datasets';
const SR_LEGACY_URL = `${DATASETS}/FoodData_Central_sr_legacy_food_json_2018-04.zip`;
const FOUNDATION_URL = `${DATASETS}/FoodData_Central_foundation_food_json_2026-04-30.zip`;
const ROWS_PER_INSERT = 500;

/** per100gFrom() from the edge function's TypeScript source, bundled in memory. */
async function loadPer100gFrom() {
  const { outputFiles } = await build({
    entryPoints: [join(repoRoot, 'supabase', 'functions', 'dish-breakdown', 'usda.ts')],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    logLevel: 'warning',
  });
  const source = Buffer.from(outputFiles[0].text).toString('base64');
  return (await import(`data:text/javascript;base64,${source}`)).per100gFrom;
}

/** Downloads one dataset zip and returns its foods array. */
async function downloadFoods(url, dir) {
  console.log(`Downloading ${url}`);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} returned HTTP ${res.status}`);
  const zip = join(dir, 'dataset.zip');
  writeFileSync(zip, Buffer.from(await res.arrayBuffer()));
  const out = join(dir, 'json');
  execFileSync('unzip', ['-o', '-q', zip, '-d', out]);
  const file = readdirSync(out).find((f) => f.endsWith('.json'));
  if (!file) throw new Error(`${url} held no JSON file`);
  const json = JSON.parse(readFileSync(join(out, file), 'utf8'));
  rmSync(dir, { recursive: true, force: true });
  // { "SRLegacyFoods": [...] } or { "FoundationFoods": [...] }
  return Object.values(json)[0];
}

const sqlText = (s) => `'${s.replace(/'/g, "''")}'`;

const per100gFrom = await loadPer100gFrom();
const work = mkdtempSync(join(tmpdir(), 'nutrio-usda-'));
const rows = [];
let skipped = 0;
try {
  for (const url of [SR_LEGACY_URL, FOUNDATION_URL]) {
    const foods = await downloadFoods(url, mkdtempSync(join(work, 'set-')));
    // The 2026-04 Foundation file ends in null entries.
    for (const food of foods.filter(Boolean)) {
      const per100g = per100gFrom({
        fdcId: food.fdcId,
        description: food.description,
        dataType: food.dataType,
        // Bulk files nest the nutrient id; the API flattens it.
        foodNutrients: (food.foodNutrients ?? []).map((n) => ({ nutrientId: n.nutrient?.id, value: n.amount })),
      });
      if (!per100g || !food.description || (food.dataType !== 'SR Legacy' && food.dataType !== 'Foundation')) {
        skipped++;
        continue;
      }
      const p = per100g;
      rows.push(
        `(${food.fdcId}, ${sqlText(food.dataType)}, ${sqlText(food.description.trim())}, ${p.kcal}, ` +
          `${p.protein}, ${p.carbs}, ${p.fat}, ${p.fibre}, ${p.sugar}, ${p.sodiumMg}, ${p.satFat})`
      );
    }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

const columns = 'fdc_id, data_type, description, kcal, protein, carbs, fat, fibre, sugar, sodium_mg, sat_fat';
const inserts = [];
for (let i = 0; i < rows.length; i += ROWS_PER_INSERT) {
  inserts.push(`INSERT INTO usda.foods (${columns}) VALUES\n${rows.slice(i, i + ROWS_PER_INSERT).join(',\n')};`);
}

const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14);
const outfile = process.argv[2] ?? join(repoRoot, 'supabase', 'migrations', `${stamp}_usda_foods_data.sql`);
writeFileSync(
  outfile,
  [
    '-- Generated by scripts/import-usda.mjs from USDA FoodData Central (CC0):',
    `--   ${SR_LEGACY_URL}`,
    `--   ${FOUNDATION_URL}`,
    '-- Do not edit by hand; re-run the script for a new snapshot.',
    '',
    'TRUNCATE usda.foods;',
    ...inserts,
    '',
  ].join('\n')
);
console.log(`Wrote ${rows.length} foods (${skipped} skipped) -> ${outfile}`);
