// Helper to make food item with Atwater check
function makeItem(def) {
  const p = Number(def.p.toFixed(1));
  const c = Number(def.c.toFixed(1));
  const f = Number(def.f.toFixed(1));
  const computedKcal = Math.round(4 * p + 4 * c + 9 * f);
  const kcal100g = def.kcal ? def.kcal : computedKcal;

  // Ensure delta is within 5
  if (Math.abs(computedKcal - kcal100g) > 6) {
    throw new Error(`Atwater check failed for ${def.name}: computed ${computedKcal}, given ${kcal100g}`);
  }

  const defaultGrams = def.servingGrams || 200;
  const defaultKcal = Math.round((kcal100g * defaultGrams) / 100);

  return {
    id: def.id,
    name: def.name,
    nameAr: def.nameAr,
    brand: def.brand,
    brandId: def.brandId,
    brandCategory: def.brandCategory,
    category: def.category || def.brandCategory,
    cuisineTags: def.tags || ['Saudi', 'Fast Food'],
    region: 'SA',
    kcal100g,
    protein100g: p,
    carb100g: c,
    fat100g: f,
    fibre100g: def.fibre || 1.0,
    sugar100g: def.sugar || 1.0,
    sodiumMg100g: def.sodium || 400,
    satFat100g: def.satFat || Math.round(f * 0.3 * 10) / 10,
    source: 'sfda',
    sourceRef: 'SFDA_RESTAURANT_CALORIE_MANDATE_2024',
    confidence: 0.98,
    oilAddedG: def.oil || Math.round(f * 0.6 * 10) / 10,
    servings: [
      { label: def.servingLabel || '1 Standard Serving', grams: defaultGrams, isDefault: true, kcal: defaultKcal },
      { label: '100g', grams: 100, isDefault: false, kcal: kcal100g },
    ],
  };
}

