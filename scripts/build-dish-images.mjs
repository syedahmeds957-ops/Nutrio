// Writes apps/mobile/src/tracker/dishImages.generated.ts from the photos that
// exist in apps/mobile/assets/dishes/. Metro only bundles images it can see in
// a static require(), and a require() of a missing file breaks the bundle, so
// the map lists exactly what is on disk. Run it after adding or removing a photo.
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'apps/mobile/assets/dishes');
const out = path.join(root, 'apps/mobile/src/tracker/dishImages.generated.ts');

const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.jpg')).sort() : [];
const lines = files.map((f) => `  '${f.replace(/\.jpg$/, '')}': require('../../assets/dishes/${f}'),`);

writeFileSync(
  out,
  [
    '// Generated by scripts/build-dish-images.mjs. Do not edit by hand.',
    '// Credits for each photo are in assets/dishes/CREDITS.md.',
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    'export const DISH_IMAGES: Record<string, ImageSourcePropType> = {',
    ...lines,
    '};',
    '',
  ].join('\n'),
);
console.log(`dishImages.generated.ts: ${files.length} photo(s)`);
