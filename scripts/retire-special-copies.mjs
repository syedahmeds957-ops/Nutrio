#!/usr/bin/env node
/**
 * Retires the "Special <dish>" rows of the generated Pakistani restaurant menus.
 *
 * Each is a near-clone of "<dish>" on the same brand (same portion, calories within about 1%), so a
 * menu showed every dish twice. They are retired rather than deleted: ids are positional or explicit
 * and saved presets reference them, so `resolveFoodId` redirects a retired id to the dish it copies.
 *
 * Writes packages/food-db/src/data/retired-special-copies.ts from the BUILT catalogue
 * (`npm run build` first). Idempotent. `--check` exits 1 if the file would change.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'packages/food-db/src/data/retired-special-copies.ts');
const db = await import(join(root, 'packages/food-db/dist/data/pakistani-restaurants-expanded.data.js'));

const items = db.PAKISTANI_EXPANDED_RESTAURANTS_DATA;
const byBrandName = new Map(items.map((item) => [`${item.brand}||${item.name}`, item]));
const rows = [];
for (const item of items) {
  if (!item.name.startsWith('Special ')) continue;
  const base = byBrandName.get(`${item.brand}||${item.name.replace(/^Special /, '')}`);
  // A "Special" dish with no plain twin on the same menu is a dish of its own: keep it.
  if (!base || !base.id || !item.id || base.id === item.id) continue;
  rows.push({ id: item.id, base: base.id, brand: item.brand, name: item.name });
}

const body = rows.map((row) => `  ${JSON.stringify(row.id)}: ${JSON.stringify(row.base)}, // ${row.brand}: ${row.name}`).join('\n');
const out = `// Generated by scripts/retire-special-copies.mjs: do not edit by hand.
// ${rows.length} "Special <dish>" rows retired in favour of the plain dish on the same menu.
// Merged into RETIRED_DUPLICATE_IDS by retired-duplicates.ts.
export const RETIRED_SPECIAL_COPIES: Readonly<Record<string, string>> = {
${body}
};
`;

let current = '';
try { current = readFileSync(target, 'utf8'); } catch { /* first run */ }
if (process.argv.includes('--check')) {
  console.log(current === out ? 'Up to date.' : 'retired-special-copies.ts is out of date: run node scripts/retire-special-copies.mjs');
  process.exit(current === out ? 0 : 1);
}
writeFileSync(target, out);
console.log(`${rows.length} special copies retired (${items.filter((i) => i.name.startsWith('Special ')).length - rows.length} "Special" dishes kept: no plain twin).`);
