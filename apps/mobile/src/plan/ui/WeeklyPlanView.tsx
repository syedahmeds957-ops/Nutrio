import React, { useMemo, useState } from 'react';
import {
  ScrollView,
  StyleSheet,
  Text,
  TouchableOpacity,
  View,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { BackButton } from '../../ui/BackButton.js';
import {
  DailyMealPlanResult,
  generateMealSwaps,
  MealPlanSolverInput,
  MealSwapOption,
  MealSwapResult,
  PlannedMealSlot,
  SolverFoodCandidate,
  solveDailyMealPlan,
} from '@nutrio/nutrition-core';
import { mealPlanFoodPool } from '../mealPlanPool.js';
import { MacroStatus, planMacroStatus } from '../planMacroStatus.js';
import { PlannedMealSlotCard } from './PlannedMealSlotCard.js';
import { MealSwapModal } from './MealSwapModal.js';
import { useTheme, commonRadii } from '../../theme.js';
import { useRegion } from '../../common/region/index.js';
import { useTranslation, useTextDirection } from '../../i18n/index.js';
import { Icon } from '../../ui/Icon.js';
import { planWeekFor } from '../weeklyPlanWeek.js';

interface WeeklyPlanViewProps {
  solverInput: MealPlanSolverInput;
  onBackToDashboard: () => void;
}

// Seven positional slots: the plan for slot i is generated by index and holds no
// weekday, so the displayed week can start on any day (see planWeekFor).
const DAYS_OF_WEEK = [0, 1, 2, 3, 4, 5, 6];

export const WeeklyPlanView: React.FC<WeeklyPlanViewProps> = ({
  solverInput,
  onBackToDashboard,
}) => {
  const { theme, isDark } = useTheme();
  const { activeRegion } = useRegion();

  const { t } = useTranslation();
  const dir = useTextDirection();
  const isSaudi = activeRegion === 'SA';
  const regionalFoodPool: SolverFoodCandidate[] = mealPlanFoodPool(isSaudi ? 'SA' : 'PK');

  // Generate a distinct or calibrated 7-day schedule with daily variety
  // The region is passed explicitly rather than left for the solver to infer
  // from the pool. Diet & Basics foods are region-neutral and merge into both
  // catalogues, so the Pakistani pool contains a few Saudi dishes — enough to
  // fool a "does this pool contain any Saudi food" check.
  const [weekPlans, setWeekPlans] = useState<DailyMealPlanResult[]>(() => {
    return DAYS_OF_WEEK.map((_, dayIndex) =>
      solveDailyMealPlan(solverInput, regionalFoodPool, { dayIndex, region: activeRegion })
    );
  });

  // Re-generate if region changes
  React.useEffect(() => {
    setWeekPlans(
      DAYS_OF_WEEK.map((_, dayIndex) =>
        solveDailyMealPlan(solverInput, regionalFoodPool, { dayIndex, region: activeRegion })
      )
    );
  }, [activeRegion]);

  const planWeek = useMemo(() => planWeekFor(activeRegion), [activeRegion]);
  const weekKeys = planWeek.dateKeys;
  const dayKeys = planWeek.weekdays;
  const [selectedDayIndex, setSelectedDayIndex] = useState(() => planWeek.todayIndex);
  // A region switch moves the week boundary, so reopen on today's new position.
  React.useEffect(() => {
    setSelectedDayIndex(planWeek.todayIndex);
  }, [planWeek]);

  // Swap modal state
  const [activeSlotToSwap, setActiveSlotToSwap] = useState<PlannedMealSlot | null>(null);
  const [activeSwapResult, setActiveSwapResult] = useState<MealSwapResult | null>(null);



  const currentDayPlan = weekPlans[selectedDayIndex];
  const macroStatus = planMacroStatus(currentDayPlan);
  const offTargetColor = isDark ? '#F87171' : '#B91C1C';
  const targetLine = (s: MacroStatus) => (
    <Text style={[styles.macroTarget, { color: s.isOff ? offTargetColor : theme.colors.textMuted }]} numberOfLines={1}>
      {t('plan.weekly.ofTarget', { grams: Math.round(s.target) })}
    </Text>
  );

  const handleOpenSwap = (slot: PlannedMealSlot) => {
    const swap = generateMealSwaps(
      slot,
      solverInput,
      regionalFoodPool
    );
    setActiveSlotToSwap(slot);
    setActiveSwapResult(swap);
  };

  const handleApplySwap = (option: MealSwapOption) => {
    if (!activeSlotToSwap) return;

    setWeekPlans((prev) => {
      const updated = [...prev];
      const dayPlan = { ...updated[selectedDayIndex] };
      const slotIndex = dayPlan.meals.findIndex(
        (m) => m.slot === activeSlotToSwap.slot
      );

      if (slotIndex >= 0) {
        const updatedMeals = [...dayPlan.meals];
        updatedMeals[slotIndex] = {
          ...updatedMeals[slotIndex],
          title: option.title,
          actualCalories: option.calories,
          items: option.items,
        };

        const newActualCalories = updatedMeals.reduce(
          (sum, m) => sum + m.actualCalories,
          0
        );
        const newCalorieDeviationPct = Number(
          (
            ((newActualCalories - dayPlan.targetCalories) /
              dayPlan.targetCalories) *
            100
          ).toFixed(1)
        );

        dayPlan.meals = updatedMeals;
        dayPlan.actualCalories = newActualCalories;
        dayPlan.calorieDeviationPct = newCalorieDeviationPct;
        dayPlan.isWithinTolerance = Math.abs(newCalorieDeviationPct) <= 5.0;

        const allItems = updatedMeals.flatMap((m) => m.items);
        dayPlan.actualProteinGrams = Number(
          allItems.reduce((s, i) => s + i.proteinGrams, 0).toFixed(1)
        );
        dayPlan.actualFatGrams = Number(
          allItems.reduce((s, i) => s + i.fatGrams, 0).toFixed(1)
        );
        dayPlan.actualCarbGrams = Number(
          allItems.reduce((s, i) => s + i.carbGrams, 0).toFixed(1)
        );
        dayPlan.totalOilAddedG = Number(
          allItems.reduce((s, i) => s + i.oilAddedG, 0).toFixed(1)
        );

        updated[selectedDayIndex] = dayPlan;
      }
      return updated;
    });

    setActiveSlotToSwap(null);
    setActiveSwapResult(null);
  };

  return (
    <SafeAreaView style={[styles.safeArea, { backgroundColor: theme.colors.canvas }]}>
      {/* Top Nav Bar */}
      <View
        style={[
          styles.topNav,
          {
            backgroundColor: theme.colors.surface,
            borderBottomColor: theme.colors.border,
          },
        ]}
      >
        <BackButton variant="icon" onPress={onBackToDashboard} />
      </View>

      {/* Horizontal Day Selector */}
      <View
        style={[
          styles.daySelectorWrapper,
          {
            backgroundColor: theme.colors.surface,
            borderBottomColor: theme.colors.border,
          },
        ]}
      >
        <View style={styles.daySelectorPad}>
          {DAYS_OF_WEEK.map((idx) => {
            const isSelected = idx === selectedDayIndex;
            const shortName = t(`common.weekdayAbbrev.${dayKeys[idx]}`);
            return (
              <TouchableOpacity
                key={idx}
                style={[
                  styles.dayTab,
                  isSelected
                    ? {
                        backgroundColor: theme.colors.primaryLime,
                        borderColor: theme.colors.primaryLime,
                      }
                    : {
                        backgroundColor: theme.colors.surfaceSecondary,
                        borderColor: theme.colors.border,
                      },
                ]}
                onPress={() => setSelectedDayIndex(idx)}
                activeOpacity={0.7}
              >
                <Text
                  numberOfLines={1}
                  adjustsFontSizeToFit
                  minimumFontScale={0.7}
                  style={[
                    styles.dayTabShort,
                    {
                      color: isSelected ? theme.colors.limeText : theme.colors.textSecondary,
                    },
                  ]}
                >
                  {shortName}
                </Text>
                <Text
                  style={[
                    styles.dayTabFull,
                    {
                      color: isSelected ? theme.colors.limeText : theme.colors.textPrimary,
                    },
                  ]}
                >
                  {Number(weekKeys[idx].slice(8))}
                </Text>
                {isSelected && (
                  <View
                    style={[
                      styles.activeDot,
                      { backgroundColor: theme.colors.limeText },
                    ]}
                  />
                )}
              </TouchableOpacity>
            );
          })}
        </View>
      </View>

      <ScrollView
        style={[styles.container, { backgroundColor: theme.colors.canvas }]}
        contentContainerStyle={styles.scrollPad}
      >
        {/* Day Summary Card */}
        <View
          style={[
            styles.daySummaryCard,
            {
              backgroundColor: theme.colors.surface,
              borderColor: theme.colors.border,
            },
          ]}
        >
          <View style={styles.daySummaryHeader}>
            <View style={styles.dayHeaderTitleCol}>
              <Text
                role="heading"
                aria-level={1}
                style={[styles.dayNameLabel, { color: theme.colors.textPrimary }]}
              >
                {t('plan.weekly.dayMealPlan', {
                  day: t(`common.weekday.${dayKeys[selectedDayIndex]}`),
                })}
              </Text>
              <Text
                style={[styles.dayTargetMeta, { color: theme.colors.textSecondary }]}
              >
                {t('plan.weekly.dayTargetKcal', {
                  kcal: currentDayPlan.targetCalories,
                })}
              </Text>
            </View>

            <View
              style={[
                styles.tolerancePill,
                {
                  backgroundColor: theme.colors.limeTint,
                  borderColor: theme.colors.limeTintBorder,
                },
              ]}
            >
              <Text
                style={[
                  styles.tolerancePillText,
                  { color: theme.colors.primaryTintText },
                ]}
              >
                {t('plan.weekly.calorieDeviation', {
                  value: `${currentDayPlan.calorieDeviationPct >= 0 ? '+' : ''}${currentDayPlan.calorieDeviationPct}`,
                })}
              </Text>
            </View>
          </View>

          {/* Macro Summary Row */}
          <View style={styles.macrosRow}>
            <View
              style={[
                styles.macroCard,
                {
                  backgroundColor: theme.colors.surfaceSecondary,
                  borderColor: theme.colors.border,
                },
              ]}
            >
              <Text
                style={[styles.macroVal, { color: theme.colors.textPrimary }]}
                numberOfLines={1}
                adjustsFontSizeToFit
              >
                {currentDayPlan.actualCalories}
              </Text>
              <Text
                style={[styles.macroLabel, { color: theme.colors.textSecondary }]}
              >
                {t('common.calories')}
              </Text>
            </View>
            <View
              style={[
                styles.macroCard,
                {
                  backgroundColor: theme.colors.surfaceSecondary,
                  borderColor: theme.colors.border,
                },
              ]}
            >
              <Text
                style={[styles.macroVal, { color: theme.colors.proteinText }]}
                numberOfLines={1}
                adjustsFontSizeToFit
              >
                {t('common.gramsValue', { value: currentDayPlan.actualProteinGrams })}
              </Text>
              {targetLine(macroStatus.protein)}
              <Text
                style={[styles.macroLabel, { color: theme.colors.textSecondary }]}
              >
                {t('common.protein')}
              </Text>
            </View>
            <View
              style={[
                styles.macroCard,
                {
                  backgroundColor: theme.colors.surfaceSecondary,
                  borderColor: theme.colors.border,
                },
              ]}
            >
              <Text
                style={[styles.macroVal, { color: theme.colors.carbsText }]}
                numberOfLines={1}
                adjustsFontSizeToFit
              >
                {t('common.gramsValue', { value: currentDayPlan.actualCarbGrams })}
              </Text>
              {targetLine(macroStatus.carbs)}
              <Text
                style={[styles.macroLabel, { color: theme.colors.textSecondary }]}
              >
                {t('common.carbs')}
              </Text>
            </View>
            <View
              style={[
                styles.macroCard,
                {
                  backgroundColor: theme.colors.surfaceSecondary,
                  borderColor: theme.colors.border,
                },
              ]}
            >
              <Text
                style={[styles.macroVal, { color: theme.colors.fatText }]}
                numberOfLines={1}
                adjustsFontSizeToFit
              >
                {t('common.gramsValue', { value: currentDayPlan.actualFatGrams })}
              </Text>
              {targetLine(macroStatus.fat)}
              <Text
                style={[styles.macroLabel, { color: theme.colors.textSecondary }]}
              >
                {t('common.fat')}
              </Text>
            </View>
            <View
              style={[
                styles.macroCard,
                styles.oilCard,
                {
                  backgroundColor: theme.colors.warningLight,
                  borderColor: theme.colors.warningBorder,
                },
              ]}
            >
              <Text
                style={[styles.macroVal, styles.oilVal, { color: theme.colors.warningText }]}
                numberOfLines={1}
                adjustsFontSizeToFit
              >
                {t('common.gramsValue', { value: currentDayPlan.totalOilAddedG })}
              </Text>
              <Text
                style={[styles.oilLabel, { color: theme.colors.warningText }]}
              >
                {t('common.oil')}
              </Text>
            </View>
          </View>

          {currentDayPlan.insufficientFoodPool ? (
            <Text style={[styles.macroNote, dir.text, { color: offTargetColor }]}>
              {t('plan.weekly.notEnoughFoods')}
            </Text>
          ) : (
            <>
              {macroStatus.protein.isOff && macroStatus.protein.gapGrams < 0 && (
                <Text style={[styles.macroNote, dir.text, { color: offTargetColor }]}>
                  {t('plan.weekly.proteinShort', { grams: -macroStatus.protein.gapGrams })}
                </Text>
              )}
              {macroStatus.fat.isOff && macroStatus.fat.gapGrams > 0 && (
                <Text style={[styles.macroNote, dir.text, { color: offTargetColor }]}>
                  {t('plan.weekly.fatOver', { grams: macroStatus.fat.gapGrams })}
                </Text>
              )}
            </>
          )}
        </View>

        {/* Meal Slots */}
        <View style={styles.slotList}>
          {currentDayPlan.meals.map((mealSlot) => (
            <PlannedMealSlotCard
              key={mealSlot.slot}
              slot={mealSlot}
              onOpenSwap={() => handleOpenSwap(mealSlot)}
            />
          ))}
        </View>

      </ScrollView>

      {/* 1-Tap Macro-Matched Swap Modal */}
      <MealSwapModal
        visible={!!activeSlotToSwap && !!activeSwapResult}
        onClose={() => {
          setActiveSlotToSwap(null);
          setActiveSwapResult(null);
        }}
        originalSlot={activeSlotToSwap}
        swapResult={activeSwapResult}
        onSelectOption={handleApplySwap}
      />


    </SafeAreaView>
  );
};

