// iOS 27 UIScene lifecycle backport of the Expo SDK 58 bare template.
//
// iOS 27 traps at launch (`_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`)
// unless the app adopts the scene lifecycle. Expo 57 already ships the runtime half
// (`ExpoAppSceneDelegate`, `ExpoReactNativeFactoryProvider` in the `expo` pod), but the
// SDK 57 prebuild template still creates the window in AppDelegate. This plugin makes
// `expo prebuild` generate what the SDK 58 template does:
//   1. Info.plist: UIApplicationSceneManifest -> $(PRODUCT_MODULE_NAME).SceneDelegate
//   2. ios/<Project>/SceneDelegate.swift: `class SceneDelegate: ExpoAppSceneDelegate {}`
//      (it creates the window from the scene, starts React Native into it, and forwards
//      URL / user-activity / lifecycle events back to the AppDelegate)
//   3. AppDelegate.swift: conform to ExpoReactNativeFactoryProvider and stop creating the
//      window / starting React Native itself.
// Every step is idempotent and a no-op on an SDK 58 template. Delete this plugin when
// upgrading to SDK 58.
const {
  IOSConfig,
  withAppDelegate,
  withInfoPlist,
  withXcodeProject,
} = require('expo/config-plugins');

const SCENE_DELEGATE_SWIFT = `internal import Expo

// Generated by plugins/withSceneLifecycle.js (iOS 27 scene lifecycle).
@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {
  // Extension point for config plugins.
}
`;

const WINDOW_BLOCK =
  /\n[ \t]*#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\([\s\S]*?\)\s*\n\s*#endif[ \t]*\n/;
const WINDOW_REPLACEMENT =
  '\n    // The window is created and React Native is started by `SceneDelegate` under the\n' +
  '    // scene-based life cycle (required by iOS 27). See plugins/withSceneLifecycle.js.\n';

function withSceneManifest(config) {
  return withInfoPlist(config, (cfg) => {
    if (!cfg.modResults.UIApplicationSceneManifest) {
      cfg.modResults.UIApplicationSceneManifest = {
        UIApplicationSupportsMultipleScenes: false,
        UISceneConfigurations: {
          UIWindowSceneSessionRoleApplication: [
            {
              UISceneConfigurationName: 'Default Configuration',
              UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
            },
          ],
        },
      };
    }
    return cfg;
  });
}

function withSceneDelegateFile(config) {
  return withXcodeProject(config, (cfg) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    cfg.modResults = IOSConfig.XcodeProjectFile.createBuildSourceFile({
      project: cfg.modResults,
      nativeProjectRoot: cfg.modRequest.platformProjectRoot,
      filePath: `${projectName}/SceneDelegate.swift`,
      fileContents: SCENE_DELEGATE_SWIFT,
      overwrite: true,
    });
    return cfg;
  });
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate.');
    }
    let src = cfg.modResults.contents;

    if (!/class AppDelegate: ExpoAppDelegate[^{]*ExpoReactNativeFactoryProvider/.test(src)) {
      const next = src.replace(
        /class AppDelegate: ExpoAppDelegate(\s*\{)/,
        'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider$1',
      );
      if (next === src) {
        throw new Error('withSceneLifecycle: could not find `class AppDelegate: ExpoAppDelegate {`.');
      }
      src = next;
    }

    if (/window = UIWindow\(frame:/.test(src) || /startReactNative\(/.test(src)) {
      const next = src.replace(WINDOW_BLOCK, WINDOW_REPLACEMENT);
      if (next === src) {
        // Leaving the AppDelegate-owned window in place brings the iOS 27 launch crash back
        // (or starts React Native twice), so fail the prebuild loudly instead.
        throw new Error(
          'withSceneLifecycle: AppDelegate still creates its own window but the expected ' +
            '`#if os(iOS) || os(tvOS) ... startReactNative ... #endif` block was not found.',
        );
      }
      src = next;
    }

    cfg.modResults.contents = src;
    return cfg;
  });
}

module.exports = function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneDelegateFile(config);
  config = withSceneAppDelegate(config);
  return config;
};
